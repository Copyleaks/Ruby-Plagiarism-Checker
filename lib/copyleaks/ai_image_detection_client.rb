module Copyleaks
  class AIImageDetectionClient
    # @param [Copyleaks::HttpClient] api_client The pooled API connection (a Net::HTTP is also accepted).
    def initialize(api_client)
      @api_client = HttpClient.wrap(api_client)
    end

    # Check whether an image was generated by AI. Synchronous: the result is in the response.
    # The image is sent as multipart/form-data when the request model holds raw image bytes
    # (image:), or as JSON when it holds base64 data.
    # For more info: https://docs.copyleaks.com/reference/actions/ai-image-detector/check
    # @param [CopyleaksAuthToken] authToken Copyleaks authentication token
    # @param [String] scanId Attach your own scan Id
    # @param [CopyleaksAiImageDetectionRequestModel] submission The image and the detection options.
    # @return [Hash] The detection result. Copyleaks::CopyleaksAiImageDetectionResponseModel.from_json(result)
    #   gives typed access.
    def submit_(authToken, scanId, submission)
      raise 'scanId is Invalid, must be instance of String' if scanId.nil? || !scanId.instance_of?(String)
      if submission.nil? || !submission.instance_of?(Copyleaks::CopyleaksAiImageDetectionRequestModel)
        raise 'submission is Invalid, must be instance of type Copyleaks::CopyleaksAiImageDetectionRequestModel'
      end

      ClientUtils.verify_auth_token(authToken)

      path = "/v1/ai-image-detector/#{ClientUtils.escape_path(scanId)}/check"
      if submission.multipart?
        ClientUtils.send_request(@api_client, :post, path, 'submit_image_detection', auth_token: authToken,
                                 multipart: submission.to_multipart)
      else
        ClientUtils.send_request(@api_client, :post, path, 'submit_image_detection', auth_token: authToken,
                                 json: submission)
      end
    end

    # Same as submit_: checks whether an image was generated by AI and returns the result.
    alias check submit_

    # Submit an image URL for AI detection. Asynchronous: the server answers 201 Created right away
    # and posts the result to the webhook URL in the request when processing completes.
    # The webhook body has the same shape as the synchronous result
    # (see Copyleaks::CopyleaksAiImageDetectionResponseModel).
    # For more info: https://docs.copyleaks.com/reference/actions/ai-image-detector/submit
    # @param [CopyleaksAuthToken] authToken Copyleaks authentication token
    # @param [String] scanId Attach your own scan Id
    # @param [CopyleaksAiImageDetectionAsyncRequestModel] submission The image URL, the webhook and the options.
    # @return [Hash, nil] The response body, usually empty.
    def submit_async(authToken, scanId, submission)
      raise 'scanId is Invalid, must be instance of String' if scanId.nil? || !scanId.instance_of?(String)
      if submission.nil? || !submission.instance_of?(Copyleaks::CopyleaksAiImageDetectionAsyncRequestModel)
        raise 'submission is Invalid, must be instance of type Copyleaks::CopyleaksAiImageDetectionAsyncRequestModel'
      end

      ClientUtils.verify_auth_token(authToken)

      path = "/v1/ai-image-detector-async/#{ClientUtils.escape_path(scanId)}/submit"
      ClientUtils.send_request(@api_client, :put, path, 'submit_image_detection_async', auth_token: authToken,
                               json: submission)
    end
  end
end
